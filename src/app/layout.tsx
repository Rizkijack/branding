export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  // Never cap zoom — capping it is an accessibility failure.
  maximumScale: 5,
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#f8f7ff" },
    { media: "(prefers-color-scheme: dark)", color: "#0b0b14" },
  ],
  colorScheme: "light dark",
};

/**
 * Runs before first paint so a dark-mode visitor never sees a white flash.
 * Deliberately inline (not a static import): it must execute synchronously,
 * ahead of hydration. Reads the same storage key next-themes uses.
 */
const THEME_BOOTSTRAP = `(function(){try{var k='branding-theme';var s=localStorage.getItem(k);var m=window.matchMedia('(prefers-color-scheme: dark)').matches;var t=(s==='system'||!s)?(m?'dark':'light'):s;var d=document.documentElement;d.classList.remove('light','dark');d.classList.add(t);d.style.colorScheme=t;}catch(e){}})();`;

/* -------------------------------------------------------------------------
 * Component
 * ---------------------------------------------------------------------- */

export default function RootLayout({
  children,
}: Readonly<{ children: ReactNode }>) {
  return (
    // suppressHydrationWarning: the bootstrap script mutates <html> before
    // React hydrates, so its className will never match the server markup.
    <html
      lang="en"
      suppressHydrationWarning
      className={`${inter.variable} ${grotesk.variable} ${mono.variable} h-full`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_BOOTSTRAP }} />
      </head>

      <body className="flex min-h-full flex-col antialiased">
        <ThemeProvider>
          {/* Skip link — first thing in the tab order, revealed on focus. */}
          <a
            href="#main"
            className="sr-only focus:not-sr-only focus:fixed focus:top-4 focus:left-4 focus:z-100 focus:rounded-pill focus:bg-brand-purple focus:px-5 focus:py-2.5 focus:text-sm focus:font-semibold focus:text-white"
          >
            Skip to content
          </a>

          {/*
            The 3D layer. One WebGL context for the whole site, mounted here so
            it survives every route change. Fixed, full-screen, behind <main>,
            `pointer-events: none` and `aria-hidden` — purely decorative. Also
            the single mount point for `useThreeEnvironment()`, which wires
            scroll / pointer / route / theme / capability signals into the
            store the camera and materials read. Renders a static CSS gradient
            until the client probe resolves, and whenever 3D is off.
          */}
          <GlobalCanvas />

          <Navbar />
          <RouteProgress />

          {/* `grow` pushes the footer down on short pages. */}
          <main id="main" className="grow">
            <PageTransition>{children}</PageTransition>
          </main>

          <Footer />
        </ThemeProvider>
      </body>
    </html>
  );
}
