/**
 * ============================================================================
 * ROOT LAYOUT
 * ============================================================================
 * Server component. Responsibilities:
 *   • load fonts via next/font (self-hosted, zero layout shift)
 *   • mount the theme provider + pre-paint theme bootstrap script
 *   • establish the shared shell: Navbar → main → Footer
 *
 * The layout never re-renders on navigation, so it is the right home for
 * anything that must survive a route change (navbar scroll state, footer).
 */

import type { Metadata, Viewport } from "next";
import { Inter, JetBrains_Mono, Space_Grotesk } from "next/font/google";
import type { ReactNode } from "react";

import "./globals.css";

import { Footer } from "@/components/layout/Footer";
import { Navbar } from "@/components/layout/Navbar";
import {
  PageTransition,
  RouteProgress,
} from "@/components/motion/PageTransition";
import { GlobalCanvas } from "@/components/three/GlobalCanvas";
import { ThemeProvider } from "@/components/theme/ThemeProvider";
import { profile } from "@/data/profile";
import { SITE_URL, absoluteUrl } from "@/lib/site";

/* -------------------------------------------------------------------------
 * Fonts
 * -------------------------------------------------------------------------
 * next/font self-hosts and subsets at build time: no Google request at
 * runtime, no FOIT, and the generated `size-adjust` metrics eliminate the
 * layout shift that `display: swap` normally causes.
 * ------------------------------------------------------------------------- */

/** Body copy. */
const inter = Inter({
  subsets: ["latin"],
  variable: "--font-inter",
  display: "swap",
});

/** Headlines. More geometric than Inter, which suits the editorial feel. */
const grotesk = Space_Grotesk({
  subsets: ["latin"],
  variable: "--font-grotesk",
  display: "swap",
});

/** Code blocks and mono UI. */
const mono = JetBrains_Mono({
  subsets: ["latin"],
  variable: "--font-mono-jet",
  display: "swap",
});

/* -------------------------------------------------------------------------
 * Metadata
 * ------------------------------------------------------------------------- */

